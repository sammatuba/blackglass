#!/usr/bin/env node
/* Artifact pipeline — single source of truth: play/blackglass-phones/assets
   (see manifest.json there). This script:

     1. copies stills (png) + clips (webm/mp4) to public/artifacts/ — ONE dist
        copy shared by the platform and the legacy iframe (which points at it
        via window.ARTIFACT_BASE in its index.html; dedupe decision 2026-10-04)
     2. encodes a .webp variant of every png (sharp, q80) — the canonical
        runtime format; the png stays as the source/fallback, never shipped
        to the PWA precache
     3. emits src/games/blackglass/artifact-list.ts (id → formats present) so
        the runtime resolves URLs without importing the binaries
     4. emits src/games/tell-exam/exam-data.ts from the manifest tells — the
        E6 field-exam plays against the same planted tells

   Run after any generation session:
     node scripts/sync-artifacts.mjs */
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = fileURLToPath(new URL('.', import.meta.url))
const SRC = join(HERE, '..', 'play', 'blackglass-phones', 'assets')
const PUBLIC = join(HERE, '..', 'public', 'artifacts')
const MANIFEST = join(SRC, 'manifest.json')

const MEDIA_RE = /\.(png|webm|mp4)$/

async function toWebp(pngPath, outPath) {
  const sharp = (await import('sharp')).default
  await sharp(pngPath).webp({ quality: 80 }).toFile(outPath)
}

async function main() {
  if (!existsSync(MANIFEST)) {
    console.error(`no manifest at ${MANIFEST} — nothing to sync`)
    process.exit(1)
  }
  const manifest = JSON.parse(readFileSync(MANIFEST, 'utf8'))
  mkdirSync(PUBLIC, { recursive: true })

  const files = readdirSync(SRC).filter((f) => MEDIA_RE.test(f))
  const formats = {}
  let webpSaved = 0

  for (const f of files) {
    const id = f.replace(/\.(png|webm|mp4)$/, '')
    const ext = f.split('.').pop()
    formats[id] = formats[id] ?? []

    if (ext === 'png') {
      // png stays the source-of-truth in play/ (and the legacy standalone
      // fallback); dist gets only the webp — nothing consumes the png at
      // runtime when webp exists, so it never ships
      const outPath = join(PUBLIC, `${id}.webp`)
      await toWebp(join(SRC, f), outPath)
      if (!formats[id].includes('webp')) formats[id].push('webp')
      webpSaved += statSync(join(SRC, f)).size - statSync(outPath).size
    } else {
      cpSync(join(SRC, f), join(PUBLIC, f))
      if (!formats[id].includes(ext)) formats[id].push(ext)
    }
  }

  // voice-list.ts — voice-note audio files (public/voicenotes/), emitted even
  // when empty so the platform import always resolves
  const VOICE_SRC = join(HERE, '..', 'play', 'blackglass-phones', 'voice')
  const AUDIO_RE = /\.(mp3|wav|ogg|m4a)$/
  const voiceFiles = []
  if (existsSync(VOICE_SRC)) {
    const PUBLIC_VOICE = join(HERE, '..', 'public', 'voicenotes')
    mkdirSync(PUBLIC_VOICE, { recursive: true })
    for (const f of readdirSync(VOICE_SRC).filter((f) => AUDIO_RE.test(f))) {
      cpSync(join(VOICE_SRC, f), join(PUBLIC_VOICE, f))
      voiceFiles.push(f)
    }
  }
  const voiceTs = `/* AUTO-GENERATED by scripts/sync-artifacts.mjs — do not edit by hand.
   audio files present in public/voicenotes/. */
export const VOICE_FILES: string[] = ${JSON.stringify(voiceFiles, null, 2)}
`
  writeFileSync(join(HERE, '..', 'src', 'games', 'blackglass', 'voice-list.ts'), voiceTs)

  // artifact-list.ts — runtime URL resolution without importing binaries
  const listTs = `/* AUTO-GENERATED by scripts/sync-artifacts.mjs — do not edit by hand.
   id → media formats present in public/artifacts/ for that artifact. */
export const ARTIFACT_FORMATS: Record<string, string[]> = ${JSON.stringify(formats, null, 2)}
`
  writeFileSync(join(HERE, '..', 'src', 'games', 'blackglass', 'artifact-list.ts'), listTs)

  // exam-data.ts — E6 field-exam plays the same planted tells
  const exam = manifest.artifacts    .filter((a) => (a.tells ?? []).length > 0 && formats[a.id])
    .map((a) => ({
      id: a.id,
      title: a.title,
      what: a.what,
      aspect: a.aspect,
      tells: (a.tells ?? []).map((t) => ({ id: t.id, label: t.label, detail: t.detail, x: t.x, y: t.y })),
    }))
  const examTs = `/* AUTO-GENERATED by scripts/sync-artifacts.mjs from the artifact manifest —
   do not edit by hand. The field-exam examines the same artifacts the
   anthology plants, with the same tells, coordinates normalized 0–1. */

export interface ExamTell {
  id: string
  label: string
  detail: string
  x: number
  y: number
}

export interface ExamItem {
  id: string
  title: string
  what: string
  aspect: string
  tells: ExamTell[]
}

export const EXAM_ITEMS: ExamItem[] = ${JSON.stringify(exam, null, 2)}
`
  const examDir = join(HERE, '..', 'src', 'games', 'tell-exam')
  mkdirSync(examDir, { recursive: true })
  writeFileSync(join(examDir, 'exam-data.ts'), examTs)

  const count = Object.keys(formats).length
  console.log(`synced ${count} artifact(s) to public/artifacts/:`)
  for (const [id, fmts] of Object.entries(formats)) console.log(`  ${id}: ${fmts.join(', ')}`)
  console.log(`webp encoding saved ≈ ${(webpSaved / 1e6).toFixed(1)} MB`)
  console.log(`voice notes: ${voiceFiles.length ? voiceFiles.join(', ') : '(none yet — see GENERATE-VOICE.md)'}`)
  console.log(`exam-data.ts: ${exam.length} item(s), ${exam.reduce((n, e) => n + e.tells.length, 0)} tells`)
}

main().catch((e) => {
  console.error(e)
  process.exit(1)
})
